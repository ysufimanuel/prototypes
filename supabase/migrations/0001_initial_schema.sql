create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;
do $$ declare t text; begin
 foreach t in array array['churches','profiles','members','families','groups','events','attendance','donors','donations','volunteers','assignments','finance_categories','finance_config','income_transactions','expense_transactions','announcements','messages','deaths','websites','website_pages','website_navigation'] loop
  execute format('create trigger %I_updated_at before update on public.%I for each row execute function public.set_updated_at()',t,t);
 end loop;
end $$;

