create table public.churches (
 id bigint generated by default as identity primary key, legacy_id text unique, nama text not null,
 alamat text, kota text, email text, telepon text, superadmin_uid uuid references auth.users(id) on delete set null,
 subscription jsonb not null default '{}'::jsonb, website jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade, church_id bigint references public.churches(id) on delete set null,
 nama text, username text unique, email text, role text not null default 'user' check (role in ('user','admin','superadmin')),
 status text, last_login timestamptz, updated_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

