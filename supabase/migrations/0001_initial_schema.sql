-- Profiles: users can see their own profile; admins can see profiles in their church.
create policy profiles_select_own_or_admin on public.profiles
for select using (
  id = auth.uid()
  or (church_id = public.current_church_id() and public.is_admin_or_superadmin())
);

create policy profiles_update_self on public.profiles
for update using (id = auth.uid())
with check (id = auth.uid());

-- Churches: authenticated members can read their church; superadmin can manage it.
create policy churches_select_tenant on public.churches
for select using (id = public.current_church_id());

create policy churches_insert_superadmin on public.churches
for insert with check (public.is_superadmin());

create policy churches_update_superadmin on public.churches
for update using (id = public.current_church_id() and public.is_superadmin())
with check (id = public.current_church_id());

